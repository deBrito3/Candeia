// Reference solution: lights every lamp and uses every required concept. Not shipped with the game.
public static class RoomLight
{
    public static int Watts()
    {
        int watts = 60;
        return watts;
    }

    public static double Voltage()
    {
        double volts = 220.0;
        return volts;
    }

    public static bool StartsOn()
    {
        bool on = true;
        return on;
    }

    public static string Model()
    {
        string model = "CND-60";
        return model;
    }
}
